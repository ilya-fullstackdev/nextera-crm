import { revalidatePath } from "next/cache";

/**
 * Сбрасывает кеш всех разделов CRM.
 *
 * Один лид виден сразу в нескольких вкладках (Лиды, Воронка, Отказы,
 * Переданные, Сделки, Переговоры, Главная, Компании, Контакты).
 * После удаления или смены статуса он должен исчезнуть из них всех, а не
 * только из той, где выполнили действие, — поэтому инвалидируем layout
 * целиком: это помечает к обновлению все страницы под /crm.
 */
export function revalidateCrm() {
  revalidatePath("/crm", "layout");
}
